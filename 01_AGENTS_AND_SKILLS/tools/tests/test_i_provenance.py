def test_extracted_text_is_derived_and_regenerable(ws, cli, indexed):
    derived = extracted_dir(ws)
    before = hash_tree(derived, skip_names=(".gitkeep",))
    assert before
    shutil.rmtree(derived)
    assert cli("index", "--subject", "algo").code == EXIT_OK
    after = hash_tree(derived, skip_names=(".gitkeep",))
    assert set(after) == set(before), "a missing derived file is re-derived without --force"


# ------------------------------------------------------------------------- scanned PDFs and OCR


@needs_pypdf
def test_a_scanned_pdf_is_recorded_as_needing_ocr_not_as_empty(ws, indexed):
    entry = next(
        item for item in index_entries(ws).values()
        if item["relative_path"].endswith("sample_scanned.pdf")
    )
    extraction = entry["extraction"]
    assert extraction["likely_scanned"] is True
    assert extraction["needs_ocr"] is True
    assert extraction["warnings"], "silence would read as 'this document is empty'"
    assert any("OCR" in warning for warning in extraction["warnings"])
    assert entry["extracted_text_path"] is None, (
        "no text file is written at all, so nothing can be mistaken for the document's content"
    )
    assert entry["pages"] == 1, "the page count is real information and is kept"
    assert entry["sha256"] and entry["bytes"] > 0


