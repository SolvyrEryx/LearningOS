def test_indexing_appends_one_event_per_processed_source(ws, cli, indexed):
    workspace = Workspace.at(ws)
    events, findings = events_mod.read_events(workspace, types=["source_indexed"])
    assert findings == []
    assert len(events) == 4
    payloads = {event["payload"]["source_id"]: event["payload"] for event in events}
    assert set(payloads) == set(index_entries(ws))
    assert all(payload["skipped_unchanged"] is False for payload in payloads.values())
    assert all(event["actor"] == "tool" for event in events)
    assert all(event["subject_id"] == "algo" for event in events)

    assert cli("index", "--subject", "algo").code == EXIT_OK
    again, _ = events_mod.read_events(workspace, types=["source_indexed"])
    assert len(again) == 4, "an unchanged source is not evidence of anything new"


