"""Test I — provenance and extraction honesty.

The question this file answers is "can a claim be traced back to a page?". That needs four things
to hold at once: a stable id, an untouched original, derived text that says where it came from,
and an honest record when extraction failed. The last one is the easiest to get wrong — an empty
string looks exactly like an empty document — so most of the assertions here are about the scanned
PDF rather than the readable one.

The PDF fixtures are generated by ``tests/fixtures/make_fixtures.py`` and committed; the PDF
assertions skip when ``pypdf`` is absent, and one test proves that absence is graceful rather than
fatal.
"""

from __future__ import annotations

import builtins
import json
import shutil
import time
from pathlib import Path

import pytest

from common import (
    EXIT_OK,
    EXIT_USAGE,
    EXIT_VALIDATION,
    SOURCE_ID_RE,
    Workspace,
    hash_tree,
    sha256_file,
)
from ingestion import extract as extract_mod
from ingestion import indexer as indexer_mod
from memory import events as events_mod
from memory import store

FIXTURES = Path(__file__).resolve().parent / "fixtures"
TEXT_FIXTURES = ("syllabus.txt", "notes.md")
PDF_FIXTURES = ("sample_text.pdf", "sample_scanned.pdf")

pypdf_available = extract_mod.pypdf_available()[0]
needs_pypdf = pytest.mark.skipif(
    not pypdf_available, reason="pypdf is an optional dependency and is not installed"
)


def sources_dir(ws: Path, subject_id: str = "algo") -> Path:
    return ws / "02_KNOWLEDGE/subjects" / subject_id / "source_materials"


def extracted_dir(ws: Path, subject_id: str = "algo") -> Path:
    return ws / "02_KNOWLEDGE/subjects" / subject_id / "extracted_text"


def place(ws: Path, *names: str, subject_id: str = "algo") -> list[Path]:
    target = sources_dir(ws, subject_id)
    target.mkdir(parents=True, exist_ok=True)
    placed = []
    for name in names:
        destination = target / name
        shutil.copy2(FIXTURES / name, destination)
        placed.append(destination)
    return placed


def index_entries(ws: Path, subject_id: str = "algo") -> dict[str, dict]:
    data = json.loads(
        (ws / "02_KNOWLEDGE/subjects" / subject_id / "source_index.json").read_text(
            encoding="utf-8"
        )
    )
    return {entry["source_id"]: entry for entry in data["sources"]}


@pytest.fixture
def indexed(ws, cli, seed_subject):
    """A subject with every fixture kind in place and indexed once."""
    seed_subject("algo", slugs=("sorting", "recursion"))
    place(ws, *TEXT_FIXTURES, *PDF_FIXTURES)
    result = cli("index", "--subject", "algo")
    assert result.code == EXIT_OK, result.text
    return result


# -------------------------------------------------------------------------------- the index itself


def test_index_records_one_entry_per_source_with_hash_size_and_id(ws, indexed):
    entries = index_entries(ws)
    assert len(entries) == 4, "every file in source_materials is indexed, readable or not"
    by_path = {entry["relative_path"]: entry for entry in entries.values()}
    for name in (*TEXT_FIXTURES, *PDF_FIXTURES):
        relative = f"02_KNOWLEDGE/subjects/algo/source_materials/{name}"
        entry = by_path[relative]
        assert SOURCE_ID_RE.match(entry["source_id"]), entry["source_id"]
        assert entry["sha256"] == sha256_file(sources_dir(ws) / name)
        assert entry["bytes"] == (sources_dir(ws) / name).stat().st_size
        assert entry["mtime_iso"].endswith("Z")
        assert entry["extraction"]["tool"] in ("builtin-text", "pypdf", "none")


def test_the_index_validates_and_so_does_the_workspace(ws, cli, indexed):
    workspace = Workspace.at(ws)
    assert store.load_source_index(workspace, "algo", required=True) is not None
    assert cli("validate").code == EXIT_OK


def test_source_id_is_derived_from_the_path_so_it_survives_an_edit(ws, cli, indexed):
    """A corrected chapter keeps its id: that is what makes an old citation still resolve."""
    before = index_entries(ws)
    target = sources_dir(ws) / "notes.md"
    identifier = indexer_mod.source_id_for(Workspace.at(ws), target)
    assert identifier in before

    target.write_text(
        before_text := "# Merge sort, corrected\n\nT(n) = 2T(n/2) + n, and the merge is linear.\n",
        encoding="utf-8",
    )
    assert cli("index", "--subject", "algo").code == EXIT_OK
    after = index_entries(ws)
    assert identifier in after, "the id is path-derived, so editing the file keeps it"
    assert after[identifier]["sha256"] != before[identifier]["sha256"]
    assert before_text.split("\n")[0] in (
        extracted_dir(ws) / f"{identifier}.txt"
    ).read_text(encoding="utf-8")


def test_a_concept_source_ref_still_resolves_after_a_reindex(ws, cli, indexed):
    workspace = Workspace.at(ws)
    identifier = index_entries(ws)
    chosen = next(
        source_id for source_id, entry in identifier.items() if entry["relative_path"].endswith(
            "syllabus.txt"
        )
    )
    record = store.get_concept_record(workspace, "algo", "algo:sorting")
    record["source_refs"] = [{"source_id": chosen, "locator": {"line": 4}}]
    store.put_concept_record(workspace, "algo", record)

    (sources_dir(ws) / "notes.md").write_text("# changed\n", encoding="utf-8")
    assert cli("index", "--subject", "algo", "--force").code == EXIT_OK

    assert chosen in index_entries(ws), "the citation target must still be in the index"
    reloaded = store.get_concept_record(Workspace.at(ws), "algo", "algo:sorting")
    assert reloaded["source_refs"][0]["source_id"] == chosen
    assert cli("validate").code == EXIT_OK


# ------------------------------------------------------------------------------- derived text


def test_extracted_text_carries_the_provenance_header(ws, indexed):
    entries = index_entries(ws)
    checked = 0
    for entry in entries.values():
        path = entry["extracted_text_path"]
        if not path:
            continue
        text = (ws / path).read_text(encoding="utf-8")
        head = text.splitlines()[:5]
        assert head[0] == f"# source_id: {entry['source_id']}"
        assert head[1] == f"# source_path: {entry['relative_path']}"
        assert head[2].startswith("# extracted_at: ")
        assert head[3].startswith("# tool: ")
        assert head[4].startswith("# tool_version: ")
        checked += 1
    assert checked >= 2


