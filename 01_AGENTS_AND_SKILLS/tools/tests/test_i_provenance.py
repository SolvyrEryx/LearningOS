def test_reindexing_unchanged_sources_reprocesses_nothing(ws, cli, indexed):
    derived = extracted_dir(ws)
    before_mtimes = {path.name: path.stat().st_mtime_ns for path in derived.glob("*.txt")}
    index_before = sha256_file(ws / "02_KNOWLEDGE/subjects/algo/source_index.json")
    time.sleep(0.01)

    result = cli("index", "--subject", "algo")
    assert result.code == EXIT_OK, result.text
    assert "unchanged" in result.out
    assert "[extracted]" not in result.out
    assert {
        path.name: path.stat().st_mtime_ns for path in derived.glob("*.txt")
    } == before_mtimes, "an unchanged source is not re-extracted"
    assert sha256_file(ws / "02_KNOWLEDGE/subjects/algo/source_index.json") == index_before, (
        "a genuine no-op leaves the index file byte-identical"
    )


def test_editing_one_file_re_extracts_only_that_file(ws, cli, indexed):
    workspace = Workspace.at(ws)
    derived = extracted_dir(ws)
    before = {path.name: path.stat().st_mtime_ns for path in derived.glob("*.txt")}
    changed_id = indexer_mod.source_id_for(workspace, sources_dir(ws) / "syllabus.txt")
    time.sleep(0.01)

    (sources_dir(ws) / "syllabus.txt").write_text(
        "Algorithms - revised syllabus\n\nUnit 1: sorting, now with a merge-sort derivation.\n",
        encoding="utf-8",
    )
    result = cli("index", "--subject", "algo")
    assert result.code == EXIT_OK, result.text

    after = {path.name: path.stat().st_mtime_ns for path in derived.glob("*.txt")}
    assert after[f"{changed_id}.txt"] != before[f"{changed_id}.txt"]
    for name, stamp in before.items():
        if name != f"{changed_id}.txt":
            assert after[name] == stamp, f"{name} was re-extracted for no reason"
    assert result.out.count("[extracted]") == 1


