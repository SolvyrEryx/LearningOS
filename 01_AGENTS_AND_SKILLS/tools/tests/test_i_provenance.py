def test_the_inbox_is_copied_from_never_moved(ws, cli, seed_subject):
    seed_subject("algo", slugs=("sorting",))
    inbox = ws / "02_KNOWLEDGE/inbox"
    shutil.copy2(FIXTURES / "notes.md", inbox / "notes.md")
    before = hash_tree(inbox)

    listing = cli("index", "--inbox")
    assert listing.code == EXIT_OK, listing.text
    assert "notes.md" in listing.out

    planned = cli("index", "--inbox", "--assign-to", "algo")
    assert planned.code == EXIT_OK, planned.text
    assert "would copy" in planned.out
    assert not (sources_dir(ws) / "notes.md").exists(), "--copy is the explicit confirmation"

    done = cli("index", "--inbox", "--assign-to", "algo", "--copy")
    assert done.code == EXIT_OK, done.text
    assert (sources_dir(ws) / "notes.md").is_file()
    assert hash_tree(inbox) == before, "nothing is ever moved or deleted from the inbox"
    assert index_entries(ws), "the newly assigned source is indexed in the same run"


