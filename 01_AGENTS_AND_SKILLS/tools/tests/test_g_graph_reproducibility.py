"""Test G — graphs are derived, reproducible and safe to throw away.

If a graph cannot be regenerated byte for byte it is not derived state, it is data — and data that
only exists inside a generated file is data waiting to be lost. So the claims under test are:
deleting the graphs directory costs nothing, regenerating from unchanged memory produces identical
Mermaid text, and the one field that legitimately moves between runs is ``generated_at``.

The renderer half matters for the same reason: a missing ``mmdc`` must cost the picture and
nothing else.
"""

from __future__ import annotations

import json
import random
import shutil
from pathlib import Path

import pytest

from common import (
    EXIT_MISSING_OPTIONAL_DEP,
    EXIT_OK,
    Workspace,
    hash_tree,
    sha256_file,
)
from graphs import build as graph_build
from graphs import mermaid as mermaid_mod
from graphs import render as render_mod
from memory import mastery

KINDS = ("concept_prerequisite", "learner_mastery", "misconception", "progress")


@pytest.fixture
def drawn(ws, cli, seed_subject):
    """A subject with evidence and a first full set of graphs on disk."""
    seed_subject("algo", slugs=("sorting", "recursion", "big-o"))
    workspace = Workspace.at(ws)
    mastery.record_attempt_and_save(
        workspace,
        "algo",
        "algo:sorting",
        session_id="2026-02-11-algo-01",
        outcome="independent_success",
        novelty="novel",
        delay_days=4,
    )
    assert cli("update-graphs", "--all").code == EXIT_OK
    return workspace


def mmd_texts(ws: Path) -> dict[str, str]:
    return {
        path.relative_to(ws).as_posix(): path.read_text(encoding="utf-8")
        for path in sorted((ws / "03_MEMORY/graphs").rglob("*.mmd"))
    }


def graph_jsons(ws: Path) -> dict[str, dict]:
    found = {}
    for path in sorted((ws / "03_MEMORY/graphs").rglob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        data.pop("generated_at", None)
        found[path.relative_to(ws).as_posix()] = data
    return found


# ------------------------------------------------------------------------------- reproducibility


def test_deleting_the_graphs_directory_is_safe_and_recoverable(ws, cli, drawn):
    before_mmd = mmd_texts(ws)
    before_json = graph_jsons(ws)
    assert len(before_mmd) == 5, "four per-subject kinds plus the cross-subject graph"

    shutil.rmtree(ws / "03_MEMORY/graphs/algo")
    assert cli("validate").code == EXIT_OK, "a missing derived artefact is not an error"

    result = cli("update-graphs", "--all")
    assert result.code == EXIT_OK, result.text
    assert mmd_texts(ws) == before_mmd, "the Mermaid text is a pure function of the memory"
    assert graph_jsons(ws) == before_json, (
        "the artefact is identical once the one moving field, generated_at, is removed"
    )


def test_running_twice_without_touching_memory_changes_no_mmd(ws, cli, drawn):
    before = hash_tree(ws / "03_MEMORY/graphs")
    assert cli("update-graphs", "--all").code == EXIT_OK
    after = hash_tree(ws / "03_MEMORY/graphs")
    mmd_before = {k: v for k, v in before.items() if k.endswith(".mmd")}
    mmd_after = {k: v for k, v in after.items() if k.endswith(".mmd")}
    assert mmd_after == mmd_before
    assert set(after) == set(before)


def test_generated_at_is_the_only_field_that_moves(ws, cli, drawn):
    path = ws / "03_MEMORY/graphs/algo/learner_mastery.json"
    first = json.loads(path.read_text(encoding="utf-8"))
    assert cli("update-graphs", "--subject", "algo", "--kinds", "learner_mastery").code == EXIT_OK
    second = json.loads(path.read_text(encoding="utf-8"))
    differing = {key for key in set(first) | set(second) if first.get(key) != second.get(key)}
    assert differing <= {"generated_at"}, differing
    assert second["generated_at"].endswith("Z")


def test_changing_memory_changes_the_graph(ws, cli, drawn):
    before = (ws / "03_MEMORY/graphs/algo/learner_mastery.mmd").read_text(encoding="utf-8")
    mastery.record_attempt_and_save(
        drawn,
        "algo",
        "algo:recursion",
        session_id="2026-02-12-algo-01",
        outcome="fail",
        novelty="variant",
    )
    assert cli("update-graphs", "--subject", "algo", "--kinds", "learner_mastery").code == EXIT_OK
    after = (ws / "03_MEMORY/graphs/algo/learner_mastery.mmd").read_text(encoding="utf-8")
    assert after != before
    assert "needs review" in after, "the graph follows the evidence"


def test_source_fingerprints_name_the_state_the_graph_was_drawn_from(ws, drawn):
    graph = json.loads(
        (ws / "03_MEMORY/graphs/algo/learner_mastery.json").read_text(encoding="utf-8")
    )
    assert graph["source_fingerprints"], "a picture should say which state it came from"
    for relative, fingerprint in graph["source_fingerprints"].items():
        assert fingerprint == f"sha256:{sha256_file(ws / relative)}"
        assert relative.startswith("03_MEMORY/subjects/algo/")


def test_to_mermaid_is_pure_and_order_independent(ws, drawn):
    graph = graph_build.build_graph(drawn, "algo", "concept_prerequisite")
    first = mermaid_mod.to_mermaid(graph)
    assert mermaid_mod.to_mermaid(graph) == first, "same input, same output"

    shuffled = json.loads(json.dumps(graph))
    random.Random(7).shuffle(shuffled["nodes"])
    random.Random(8).shuffle(shuffled["edges"])
    shuffled["generated_at"] = "2030-01-01T00:00:00Z"
    assert mermaid_mod.to_mermaid(shuffled) == first, (
        "nodes and edges are emitted in sorted order, and no timestamp reaches the .mmd"
    )


def test_no_timestamp_leaks_into_the_mermaid_text(ws, drawn):
    for text in mmd_texts(ws).values():
        assert "generated_at" not in text
        assert "Z\n" not in text.replace("\r", ""), "a stamp would break byte-stability"


# ----------------------------------------------------------------------- the renderer is optional


def test_without_mmdc_the_run_still_succeeds_and_says_what_it_skipped(ws, cli, drawn, monkeypatch):
    monkeypatch.setattr(render_mod, "renderer_path", lambda: None)
    result = cli("update-graphs", "--subject", "algo", "--kinds", "progress")
    assert result.code == EXIT_OK, result.text
    assert render_mod.SVG_SKIP_NOTICE in result.out
    assert result.out.count(render_mod.SVG_SKIP_NOTICE) == 1, "once per run, not once per file"
    assert (ws / "03_MEMORY/graphs/algo/progress.mmd").is_file()
    assert (ws / "03_MEMORY/graphs/algo/progress.html").is_file()
    assert not (ws / "03_MEMORY/graphs/algo/progress.svg").exists()


def test_require_renderer_turns_the_skip_into_a_failure(ws, cli, drawn, monkeypatch):
    monkeypatch.setattr(render_mod, "renderer_path", lambda: None)
    before = hash_tree(ws / "03_MEMORY/graphs")
    result = cli("update-graphs", "--all", "--require-renderer")
    assert result.code == EXIT_MISSING_OPTIONAL_DEP
    assert "mmdc" in result.err
    assert "Install mermaid-cli yourself" in result.err, "the remedy says what to do"
    assert hash_tree(ws / "03_MEMORY/graphs") == before, "it fails before it writes"


def test_the_skip_is_recorded_in_the_event(ws, cli, drawn, monkeypatch):
    from memory import events as events_mod

    monkeypatch.setattr(render_mod, "renderer_path", lambda: None)
    assert cli("update-graphs", "--subject", "algo", "--kinds", "progress").code == EXIT_OK
    events, _findings = events_mod.read_events(drawn, types=["graph_generated"])
    assert events[-1]["payload"]["svg_skipped"] is True
    assert events[-1]["payload"]["renderer"] is None
    assert "svg" not in events[-1]["payload"]["formats"]


# --------------------------------------------------------------------------------- the HTML page


def test_the_html_page_is_self_contained_and_shows_the_source(ws, drawn):
    page = (ws / "03_MEMORY/graphs/algo/learner_mastery.html").read_text(encoding="utf-8")
    assert page.startswith("<!DOCTYPE html>")
    assert '<html lang="en">' in page
    assert "<title>" in page and "<h1>" in page
    assert '<pre class="mermaid">' in page
    assert "flowchart TD" in page, "the Mermaid source is on the page even without a renderer"
    assert "&quot;" in page or "&amp;" in page, "the source is HTML-escaped"
    assert "http://" not in page and "https://" not in page, (
        "a learning artefact makes no network requests and links to no CDN"
    )
    assert "{{TITLE}}" not in page and "{{RENDERER_BLOCK}}" not in page
    assert "Diagram not rendered" in page
    assert "mermaid.min.js" in page, "the page explains how to enable rendering"


def test_a_vendored_renderer_is_inlined(ws, drawn, tmp_path):
    vendor = tmp_path / "vendor"
    vendor.mkdir()
    (vendor / "mermaid.min.js").write_text(
        "window.mermaid = { initialize: function () { /* stub */ } };\n", encoding="utf-8"
    )
    graph = graph_build.build_graph(drawn, "algo", "learner_mastery")
    page, inlined = render_mod.render_html(
        graph,
        mermaid_mod.to_mermaid(graph),
        template_path=drawn.graph_templates / "viewer.html.tmpl",
        vendor_dir=vendor,
    )
    assert inlined is True
    assert "window.mermaid = {" in page, "inlined, not linked: the page must work offline"
    assert "startOnLoad: true" in page
    assert "Diagram not rendered" not in page


def test_the_shipped_html_template_is_the_one_being_used(ws, drawn):
    page = (ws / "03_MEMORY/graphs/algo/progress.html").read_text(encoding="utf-8")
    template = (drawn.graph_templates / "viewer.html.tmpl").read_text(encoding="utf-8")
    assert "pre.mermaid {" in template and "pre.mermaid {" in page, (
        "the generated page comes from templates/graph_templates/viewer.html.tmpl"
    )
    assert "LearningOS graph viewer template" not in page, (
        "the template's instructions to the implementer are not shipped to the learner"
    )


@pytest.mark.parametrize("kind", KINDS + ("cross_subject",))
def test_the_mermaid_frame_matches_the_shipped_template(ws, drawn, kind):
    """The templates document the static frame; the module emits it. They must not drift."""
    template = (drawn.graph_templates / f"{kind}.mmd.tmpl").read_text(encoding="utf-8")
    emitted = mermaid_mod.to_mermaid(graph_build.build_graph(drawn, "algo", kind))
    for line in template.splitlines():
        stripped = line.strip()
        if not stripped.startswith("classDef"):
            continue
        assert stripped in emitted, f"{kind}: the template declares {stripped!r}, the code does not"
    diagram_headers = [
        stripped
        for stripped in (line.strip() for line in template.splitlines())
        if stripped.startswith(("flowchart", "pie title"))
    ]
    assert diagram_headers, f"{kind}: the template has no diagram header"
    for header in diagram_headers:
        assert header in emitted
